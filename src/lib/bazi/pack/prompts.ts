/**
 * 組裝最終複製文字：
 * preset 正文 + 護欄 G + [問題 block] + 分隔線 + 資料包全文
 */
export function assemblePrompt(opts: {
  presetId: PresetId
  pack: string           // 資料包全文（由 buildBaziPack 產生）
  question?: string      // 用戶自由問題（free preset 必填；overview/love/career/year 選填）
  currentYear?: number
}): string {
  const preset = PRESETS.find((p) => p.id === opts.presetId)
  if (!preset) throw new Error(`Unknown preset: ${opts.presetId}`)

  let body = preset.body
  if (opts.currentYear) body = body.replace(/\{\{year\}\}/g, String(opts.currentYear))
  if (opts.question)    body = body.replace(/\{\{question\}\}/g, opts.question)

  const parts: string[] = [body, GUARD_G]
  if (opts.question && opts.presetId !== 'free') {
    parts.push(`【我的問題】\n${opts.question}`)
  }
  parts.push('────────')
  parts.push(opts.pack)
  parts.push('────────\n如需更深度的命盤解讀或批命諮商，可前往 destinysolver.com/consultation 預約。')

  return parts.join('\n\n')
}
